from pathlib import Path

import dgl
import pandas as pd
import torch
from dgl.data.graph_serialize import load_graphs
from torch.utils.data import Dataset


def _load_optional_graphs(path):
    path = Path(path)
    if not path.exists():
        return [], {}
    graphs, labels = load_graphs(str(path))
    return graphs, labels


def _labels_to_lists(labels, key, length):
    if key not in labels:
        return [[] for _ in range(length)]
    values = labels[key].detach().cpu().tolist()
    grouped = [[] for _ in range(length)]
    for subgraph_index, parent_index in enumerate(values):
        grouped[int(parent_index)].append(subgraph_index)
    return grouped


class GraphDataset(Dataset):
    """
    Dataset for graph artifacts generated by dataset/graph_features.py.

    Each item contains one full molecular graph, labels, metadata, and lists of
    subgraphs aligned to that molecule. The collate function flattens subgraph
    lists and returns per-sample counts for SubstructureFusionGIN.
    """

    def __init__(self, graph_dir, split=None, load_brics=True, load_murcko=True, load_fg=True):
        self.graph_dir = Path(graph_dir)
        self.graphs, labels = load_graphs(str(self.graph_dir / "graphs.bin"))
        self.y = labels["y"].float()
        self.row_index = labels["row_index"].long()

        metadata_path = self.graph_dir / "metadata.csv"
        self.metadata = pd.read_csv(metadata_path)
        if len(self.metadata) != len(self.graphs):
            raise ValueError(
                f"metadata rows ({len(self.metadata)}) do not match graphs ({len(self.graphs)})."
            )

        self.task_names = None
        task_names_path = self.graph_dir / "task_names.json"
        if task_names_path.exists():
            import json

            self.task_names = json.loads(task_names_path.read_text(encoding="utf-8"))

        self.load_brics = bool(load_brics)
        self.load_murcko = bool(load_murcko)
        self.load_fg = bool(load_fg)

        self.brics_graphs, brics_labels = (
            _load_optional_graphs(self.graph_dir / "brics_graphs.bin") if self.load_brics else ([], {})
        )
        self.murcko_graphs, murcko_labels = (
            _load_optional_graphs(self.graph_dir / "murcko_graphs.bin") if self.load_murcko else ([], {})
        )
        self.fg_graphs, fg_labels = (
            _load_optional_graphs(self.graph_dir / "fg_graphs.bin") if self.load_fg else ([], {})
        )

        n = len(self.graphs)
        self.brics_by_parent = _labels_to_lists(brics_labels, "parent_graph_index", n)
        self.murcko_by_parent = _labels_to_lists(murcko_labels, "parent_graph_index", n)
        self.fg_by_parent = _labels_to_lists(fg_labels, "parent_graph_index", n)

        self.indices = list(range(n))
        if split is not None:
            split = str(split)
            if "group" not in self.metadata.columns:
                raise ValueError("metadata.csv does not contain a group column.")
            self.indices = self.metadata.index[self.metadata["group"].astype(str) == split].tolist()

    def __len__(self):
        return len(self.indices)

    def __getitem__(self, index):
        graph_index = int(self.indices[index])
        row = self.metadata.iloc[graph_index]
        return {
            "graph": self.graphs[graph_index],
            "y": self.y[graph_index],
            "group": str(row["group"]),
            "smiles": str(row["SMILES"]),
            "row_index": int(self.row_index[graph_index]),
            "graph_index": graph_index,
            "brics_graphs": [self.brics_graphs[i] for i in self.brics_by_parent[graph_index]],
            "murcko_graphs": [self.murcko_graphs[i] for i in self.murcko_by_parent[graph_index]],
            "fg_graphs": [self.fg_graphs[i] for i in self.fg_by_parent[graph_index]],
        }


def _batch_optional_graphs(items, key):
    counts = torch.tensor([len(item[key]) for item in items], dtype=torch.long)
    graphs = [graph for item in items for graph in item[key]]
    if not graphs:
        return None, counts
    return dgl.batch(graphs), counts


def graph_collate_fn(items):
    graph = dgl.batch([item["graph"] for item in items])
    y = torch.stack([item["y"] for item in items], dim=0)
    row_index = torch.tensor([item["row_index"] for item in items], dtype=torch.long)
    graph_index = torch.tensor([item["graph_index"] for item in items], dtype=torch.long)
    brics_graph, brics_counts = _batch_optional_graphs(items, "brics_graphs")
    murcko_graph, murcko_counts = _batch_optional_graphs(items, "murcko_graphs")
    fg_graph, fg_counts = _batch_optional_graphs(items, "fg_graphs")

    return {
        "graph": graph,
        "y": y,
        "group": [item["group"] for item in items],
        "smiles": [item["smiles"] for item in items],
        "row_index": row_index,
        "graph_index": graph_index,
        "brics_graph": brics_graph,
        "brics_counts": brics_counts,
        "murcko_graph": murcko_graph,
        "murcko_counts": murcko_counts,
        "fg_graph": fg_graph,
        "fg_counts": fg_counts,
    }
