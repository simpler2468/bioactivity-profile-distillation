from pathlib import Path

import numpy as np
import torch
from torch.utils.data import Dataset


class TabularFeatureDataset(Dataset):
    """
    Dataset for .npz files generated by dataset/molecular_features.py.
    """

    def __init__(self, npz_path, split=None):
        self.npz_path = Path(npz_path)
        data = np.load(self.npz_path, allow_pickle=True)
        self.x = torch.tensor(data["X"], dtype=torch.float32)
        self.y = torch.tensor(data["y"], dtype=torch.float32)
        self.groups = data["groups"].astype(str)
        self.smiles = data["smiles"].astype(str)
        self.task_names = data["task_names"].astype(str).tolist()
        self.feature_names = data["feature_names"].astype(str).tolist()

        self.indices = np.arange(len(self.x))
        if split is not None:
            split = str(split)
            self.indices = np.where(self.groups == split)[0]

    @property
    def input_dim(self):
        return int(self.x.shape[1])

    @property
    def output_dim(self):
        return int(self.y.shape[1])

    def __len__(self):
        return int(len(self.indices))

    def __getitem__(self, index):
        row_index = int(self.indices[index])
        return {
            "x": self.x[row_index],
            "y": self.y[row_index],
            "group": str(self.groups[row_index]),
            "smiles": str(self.smiles[row_index]),
            "row_index": row_index,
        }


def tabular_collate_fn(items):
    return {
        "x": torch.stack([item["x"] for item in items], dim=0),
        "y": torch.stack([item["y"] for item in items], dim=0),
        "group": [item["group"] for item in items],
        "smiles": [item["smiles"] for item in items],
        "row_index": torch.tensor([item["row_index"] for item in items], dtype=torch.long),
    }
